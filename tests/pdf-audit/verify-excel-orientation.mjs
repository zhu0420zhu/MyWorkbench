/**
 * 验收 pdfIpc 的「Excel → PDF 页面方向」修复。
 *
 * 旧实现把方向映射到 `SelectPdfVersion` 与 `SinglePageSheets`——两者都与方向无关，
 * 实测 portrait / landscape 的 MediaBox 一字不差（均 0 0 595.30 841.89）。
 *
 * 新实现走 LibreOffice Basic 宏：导出前改写页面样式的 Width/Height。
 * 本脚本直接调用生产模块 src/main/pdf/sofficeOrient.ts 的 convertExcelOriented，
 * 断言：
 *   - landscape 首页 MediaBox 宽 > 高（842×595）
 *   - portrait  首页 MediaBox 高 > 宽（595×842）
 *   - 两者不同（方向真正生效）
 */
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { readFile, mkdir, rm } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { PDFDocument } from 'pdf-lib'
import {
  convertExcelOriented,
  cleanSofficeEnv,
  toFileUrl
} from '../../src/main/pdf/sofficeOrient.ts'

const execFileP = promisify(execFile)
const HERE = dirname(fileURLToPath(import.meta.url))
const FIX = join(HERE, 'fixtures')
const WORK = join(HERE, 'work', 'orient-verify')
await rm(WORK, { recursive: true, force: true })
await mkdir(WORK, { recursive: true })

const SOFFICE = join(process.cwd(), 'resources', 'tools', 'soffice', 'program', 'soffice.com')
console.log('soffice:', existsSync(SOFFICE) ? 'OK' : 'MISSING')

let pass = 0
let fail = 0
function check(name, cond, detail) {
  if (cond) {
    pass++
    console.log('  [PASS] ' + name + (detail ? '  ' + detail : ''))
  } else {
    fail++
    console.log('  [FAIL] ' + name + (detail ? '  ' + detail : ''))
  }
}

/* 1. 生成源工作簿（CSV → XLSX），复用审计素材 */
const csv = join(FIX, 'sheet.csv')
const srcDir = join(WORK, 'src')
await mkdir(srcDir, { recursive: true })
await execFileP(
  SOFFICE,
  ['-env:UserInstallation=' + toFileUrl(join(WORK, 'prof-conv')), '--headless', '--norestore', '--convert-to', 'xlsx', '--outdir', srcDir, csv],
  { timeout: 180000, windowsHide: true, env: cleanSofficeEnv() }
)
const srcXlsx = join(srcDir, 'sheet.xlsx')
console.log('源工作簿:', existsSync(srcXlsx) ? 'sheet.xlsx' : 'FAIL 生成失败')
if (!existsSync(srcXlsx)) process.exit(1)

const cacheDir = join(WORK, 'cache')
await mkdir(cacheDir, { recursive: true })

async function mediaBox(pdfPath) {
  const doc = await PDFDocument.load(await readFile(pdfPath))
  const s = doc.getPages()[0].getSize()
  return { pages: doc.getPageCount(), w: Math.round(s.width), h: Math.round(s.height) }
}

/* 2. landscape */
console.log('\n== landscape ==')
const outL = join(WORK, 'landscape.pdf')
const rL = await convertExcelOriented(SOFFICE, srcXlsx, outL, 'landscape', cacheDir)
console.log('  ok=' + rL.ok + (rL.stderr ? ' stderr=' + rL.stderr.slice(0, 160) : ''))
check('landscape 产出存在', rL.ok)
let boxL = null
if (rL.ok) {
  boxL = await mediaBox(outL)
  console.log('  MediaBox 首页: ' + boxL.w + '×' + boxL.h + ' (' + boxL.pages + ' 页)')
  check('landscape 宽 > 高（横向）', boxL.w > boxL.h, boxL.w + '×' + boxL.h)
  check('landscape 首页 ≈ 842×595', Math.abs(boxL.w - 842) <= 2 && Math.abs(boxL.h - 595) <= 2)
}

/* 3. portrait */
console.log('\n== portrait ==')
const outP = join(WORK, 'portrait.pdf')
const rP = await convertExcelOriented(SOFFICE, srcXlsx, outP, 'portrait', cacheDir)
console.log('  ok=' + rP.ok + (rP.stderr ? ' stderr=' + rP.stderr.slice(0, 160) : ''))
check('portrait 产出存在', rP.ok)
let boxP = null
if (rP.ok) {
  boxP = await mediaBox(outP)
  console.log('  MediaBox 首页: ' + boxP.w + '×' + boxP.h + ' (' + boxP.pages + ' 页)')
  check('portrait 高 > 宽（纵向）', boxP.h > boxP.w, boxP.w + '×' + boxP.h)
  check('portrait 首页 ≈ 595×842', Math.abs(boxP.w - 595) <= 2 && Math.abs(boxP.h - 842) <= 2)
}

/* 4. 两者必须不同 —— 旧实现的致命伤在此 */
if (boxL && boxP) {
  check('landscape 与 portrait 尺寸不同（方向真正生效）', boxL.w !== boxP.w || boxL.h !== boxP.h)
}

/* 5. auto 基线：走原生 --convert-to，不带方向参数 */
console.log('\n== auto（跟随源文件，基线对照）==')
const outA = join(WORK, 'auto.pdf')
await execFileP(
  SOFFICE,
  ['-env:UserInstallation=' + toFileUrl(join(WORK, 'prof-auto')), '--headless', '--norestore', '--convert-to', 'pdf:calc_pdf_Export', '--outdir', WORK, srcXlsx],
  { timeout: 180000, windowsHide: true, env: cleanSofficeEnv() }
).catch((e) => ({ stderr: String(e.stderr || e.message) }))
// auto 输出文件名固定为 sheet.pdf
const autoGenerated = join(WORK, 'sheet.pdf')
if (existsSync(autoGenerated)) {
  const boxA = await mediaBox(autoGenerated)
  console.log('  MediaBox 首页: ' + boxA.w + '×' + boxA.h)
  check('auto 保留源文件方向（纵向 595×842）', boxA.h > boxA.w)
} else {
  check('auto 产出存在', false)
}

console.log('\n' + '='.repeat(60))
console.log(`结果: ${pass} 项通过, ${fail} 项失败`)
console.log('='.repeat(60))
process.exit(fail ? 1 : 0)
